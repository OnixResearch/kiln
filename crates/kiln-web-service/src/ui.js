"use strict";

// Shared presentation helpers for the live console. Pure DOM/format builders:
// no network, no storage; reads window.KilnIcons and defines only window.KilnUi. Data is always
// written through textContent or attributes, never parsed as markup.
// r[impl kiln.web.readable_observations]
// r[impl kiln.web.readable_observations.scenario.failed]
// r[impl kiln.web.readable_observations.scenario.unknown]
// r[impl kiln.web.visual_design]
(() => {
  const SECOND_MS = 1000;
  const MINUTE_MS = 60 * SECOND_MS;
  const HOUR_MS = 60 * MINUTE_MS;
  const DAY_MS = 24 * HOUR_MS;
  const ONE_DECIMAL_LIMIT_MS = 10 * SECOND_MS;
  const JUST_NOW_LIMIT_MS = 45 * SECOND_MS;
  const RELATIVE_LIMIT_MS = 30 * DAY_MS;
  const NOT_RECORDED = "Not recorded";
  const SVG_NS = "http://www.w3.org/2000/svg";

  const exactNumber = new Intl.NumberFormat("en-US", { maximumFractionDigits: 3 });
  const localDateTime = new Intl.DateTimeFormat(undefined, {
    year: "numeric", month: "short", day: "numeric",
    hour: "2-digit", minute: "2-digit", second: "2-digit", timeZoneName: "short",
  });
  const shortDate = new Intl.DateTimeFormat(undefined, { year: "numeric", month: "short", day: "numeric" });
  const dayDate = new Intl.DateTimeFormat(undefined, { weekday: "short", year: "numeric", month: "short", day: "numeric" });

  // Canonical outcome -> [semantic status, human label].
  const OUTCOMES = Object.freeze({
    Success: ["success", "Passed"],
    DomainFailure: ["failure", "Failed"],
    Denied: ["failure", "Denied"],
    ProviderError: ["failure", "Provider error"],
    TimedOut: ["failure", "Timed out"],
    Cancelled: ["cancelled", "Cancelled"],
    Unknown: ["unknown", "Unknown"],
  });

  function outcomeStatus(outcome, phase) {
    if ((outcome === null || outcome === undefined || outcome === "") && phase === "queued") return { status: "queued", label: "Queued" };
    if (outcome === null || outcome === undefined || outcome === "") return { status: "unknown", label: NOT_RECORDED };
    if (outcome === "Pending") return phase === "active" ? { status: "running", label: "Running" } : { status: "queued", label: "Queued" };
    if (typeof outcome === "string" && Object.hasOwn(OUTCOMES, outcome)) {
      const [status, label] = OUTCOMES[outcome];
      return { status, label };
    }
    return { status: "unknown", label: String(outcome) };
  }

  // r[impl kiln.web.design_system] Every icon is pinned Lucide data from /icons.js
  // (window.KilnIcons, generated by scripts/import-lucide-icons.sh). No glyph is drawn here.
  const ICON_ATTRIBUTES = Object.freeze([
    ["viewBox", "0 0 24 24"], ["fill", "none"], ["stroke", "currentColor"], ["stroke-width", "2"],
    ["stroke-linecap", "round"], ["stroke-linejoin", "round"], ["aria-hidden", "true"], ["focusable", "false"], ["class", "icon"],
  ]);
  // Semantic status -> Lucide icon; unrecognised statuses read as unknown.
  const STATUS_ICONS = Object.freeze({
    success: "circle-check", failure: "circle-x", running: "loader-circle", queued: "clock",
    cancelled: "ban", unknown: "circle-question-mark", warning: "triangle-alert",
  });

  // Unknown names are programming errors: fail loudly instead of drawing a stand-in.
  function icon(name) {
    const icons = window.KilnIcons;
    if (!icons || typeof name !== "string" || !Object.hasOwn(icons, name)) throw new RangeError(`Unknown icon: ${String(name)}`);
    const svg = document.createElementNS(SVG_NS, "svg");
    for (const [key, value] of ICON_ATTRIBUTES) svg.setAttribute(key, value);
    svg.setAttribute("data-icon", name);
    for (const [tag, attributes] of icons[name]) {
      const shape = document.createElementNS(SVG_NS, tag);
      for (const [key, value] of Object.entries(attributes)) shape.setAttribute(key, value);
      svg.append(shape);
    }
    return svg;
  }
  function statusIcon(status) {
    return icon(STATUS_ICONS[Object.hasOwn(STATUS_ICONS, status) ? status : "unknown"]);
  }
  // Static markup carries <span class="icon" data-icon="name" aria-hidden="true"></span>
  // placeholders; each becomes the SVG and keeps the placeholder's classes.
  function hydrateIcons(root) {
    for (const placeholder of root.querySelectorAll("span[data-icon]")) {
      const svg = icon(placeholder.dataset.icon);
      for (const name of placeholder.classList) svg.classList.add(name);
      placeholder.replaceWith(svg);
    }
  }

  // Disclosure summary: optional leading icon, the label, and a trailing chevron that CSS turns when open.
  function disclosureSummary(label, leading) {
    const summary = document.createElement("summary");
    if (leading) summary.append(icon(leading));
    summary.append(label);
    const chevron = icon("chevron-down");
    chevron.classList.add("disclosure-chevron");
    summary.append(chevron);
    return summary;
  }

  function hidden(content) {
    const node = document.createElement("span");
    node.className = "sr-only";
    node.textContent = content;
    return node;
  }

  function statusPill(outcome, phase) {
    const { status, label } = outcomeStatus(outcome, phase);
    const pill = document.createElement("span");
    pill.className = "status-pill";
    pill.dataset.status = status;
    const text = document.createElement("span");
    text.className = "status-pill-label";
    text.textContent = label;
    pill.append(statusIcon(status), text);
    const parts = [];
    if (outcome !== null && outcome !== undefined && outcome !== "") {
      if (String(outcome) !== label) parts.push(String(outcome));
      if (outcome === "Pending" && phase) parts.push(`phase ${phase}`);
    } else if (label !== NOT_RECORDED) parts.push(`outcome not recorded, phase ${phase}`);
    const exact = parts.join(", ");
    const name = `Outcome: ${label}${exact ? ` (${exact})` : ""}`;
    pill.setAttribute("role", "img");
    pill.setAttribute("aria-label", name);
    pill.title = name;
    return pill;
  }

  function validDuration(ms) {
    return typeof ms === "number" && Number.isFinite(ms) && ms >= 0;
  }
  function formatDuration(ms) {
    if (!validDuration(ms)) return NOT_RECORDED;
    if (ms < ONE_DECIMAL_LIMIT_MS) return `${(Math.floor(ms / 100) / 10).toFixed(1)}s`;
    if (ms < MINUTE_MS) return `${Math.floor(ms / SECOND_MS)}s`;
    if (ms < HOUR_MS) return `${Math.floor(ms / MINUTE_MS)}m ${String(Math.floor((ms % MINUTE_MS) / SECOND_MS)).padStart(2, "0")}s`;
    return `${Math.floor(ms / HOUR_MS)}h ${String(Math.floor((ms % HOUR_MS) / MINUTE_MS)).padStart(2, "0")}m`;
  }
  function durationElement(ms) {
    const span = document.createElement("span");
    span.className = "duration";
    span.textContent = formatDuration(ms);
    if (!validDuration(ms)) {
      span.classList.add("not-recorded");
      span.title = "Duration not recorded";
      return span;
    }
    const exact = `${exactNumber.format(ms)} ms`;
    span.title = exact;
    span.dataset.ms = String(ms);
    span.append(hidden(` (${exact})`));
    return span;
  }

  function instant(value) {
    let ms = NaN;
    if (typeof value === "number") ms = value;
    else if (typeof value === "string" && value.trim()) ms = /^-?\d+$/.test(value.trim()) ? Number(value) : Date.parse(value);
    else if (value instanceof Date) ms = value.getTime();
    if (!Number.isFinite(ms)) return null;
    const date = new Date(ms);
    return Number.isNaN(date.valueOf()) ? null : date;
  }
  function formatRelative(value, now = Date.now()) {
    const date = instant(value);
    const reference = instant(now);
    if (!date || !reference) return NOT_RECORDED;
    const delta = reference.getTime() - date.getTime();
    const distance = Math.abs(delta);
    if (distance < JUST_NOW_LIMIT_MS) return "just now";
    if (distance > RELATIVE_LIMIT_MS) return shortDate.format(date);
    // Round to the nearest unit; switch units before rounding would reach the next one (no "60m").
    const amount = distance < HOUR_MS - MINUTE_MS / 2 ? `${Math.max(1, Math.round(distance / MINUTE_MS))}m` : distance < DAY_MS - HOUR_MS / 2 ? `${Math.round(distance / HOUR_MS)}h` : `${Math.round(distance / DAY_MS)}d`;
    return delta >= 0 ? `${amount} ago` : `in ${amount}`;
  }
  function timeElement(value) {
    const date = instant(value);
    if (!date) {
      const span = document.createElement("span");
      span.className = "relative-time not-recorded";
      span.textContent = NOT_RECORDED;
      return span;
    }
    const iso = date.toISOString();
    const exact = `${localDateTime.format(date)} · ${iso}`;
    const time = document.createElement("time");
    time.className = "relative-time";
    time.dateTime = iso;
    time.title = exact;
    time.textContent = formatRelative(date.getTime());
    time.append(hidden(` (${exact})`));
    return time;
  }

  // r[impl kiln.web.failure_first_run] Conservative, bounded error-line recognition. Presentation only:
  // callers highlight the returned line indexes over inert text and never alter the retained bytes.
  const MAX_ERROR_LINES = 1000;
  const MAX_ERROR_LINE_CHARS = 2048;
  // A word that is not part of an identifier, path, file name or hyphenated name ("error-chain", "error.rs", "error_code").
  const word = (pattern, flags = "i") => new RegExp(`(?<![\\w./\`-])(?:${pattern})(?![\\w/\`-]|\\.\\w)`, flags);
  const STRONG_ERROR_PATTERNS = Object.freeze([
    /(?<![\w./-])error(?:\[[A-Za-z]?\d+\])?:/i,
    /^\s*(?:error|fatal)\b/i,
    /\bpanicked at\b/,
    word("FAILED", ""),
    /^\s*Traceback \(most recent call last\)/,
    /(?<![\w.])[A-Z]\w*(?:Error|Exception):/,
    /\bexit(?:ed with)?(?: exit)? (?:code|status)\D{0,3}[1-9]/i,
  ]);
  const WEAK_ERROR_PATTERN = word("error|failed|fatal");
  const BENIGN_ERROR_PATTERN = /\b(?:0|no|zero|without) (?:errors?|failed|failures?|fatal)\b|\b(?:errors?|failed|failures?)[:=] ?0\b/i;
  function isErrorLine(line) {
    const sample = line.length > MAX_ERROR_LINE_CHARS ? line.slice(0, MAX_ERROR_LINE_CHARS) : line;
    if (STRONG_ERROR_PATTERNS.some((pattern) => pattern.test(sample))) return true;
    return WEAK_ERROR_PATTERN.test(sample) && !BENIGN_ERROR_PATTERN.test(sample);
  }
  function errorLines(text) {
    if (typeof text !== "string" || !text) return [];
    const lines = text.split("\n");
    const result = [];
    for (let index = 0; index < lines.length && result.length < MAX_ERROR_LINES; index++) if (isErrorLine(lines[index])) result.push(index);
    return result;
  }

  // r[impl kiln.web.project_page.scenario.untimed] Trend points: terminal runs with a recorded duration only,
  // oldest first by service ordinal. Terminal runs without timing are counted as excluded; in-progress runs are neither.
  function durationPoints(runs) {
    if (!Array.isArray(runs)) return Object.freeze({ points: Object.freeze([]), excluded: 0 });
    const ordered = [];
    const unordered = [];
    let excluded = 0;
    runs.forEach((run, index) => {
      if (!run || typeof run !== "object") return;
      const outcome = run.outcome;
      if (typeof outcome !== "string" || !outcome || outcome === "Pending") return;
      if (!Number.isSafeInteger(run.duration_ms) || run.duration_ms < 0) { excluded++; return; }
      const at = [run.completed_at_ms, run.started_at_ms, run.created_at_ms].find((value) => Number.isSafeInteger(value));
      const point = Object.freeze({ id: run.id, duration_ms: run.duration_ms, outcome, at_ms: at ?? null });
      (Number.isSafeInteger(run.ordinal) ? ordered : unordered).push({ point, ordinal: run.ordinal, index });
    });
    ordered.sort((a, b) => a.ordinal - b.ordinal || a.index - b.index);
    return Object.freeze({ points: Object.freeze([...ordered, ...unordered].map((entry) => entry.point)), excluded });
  }

  // r[impl kiln.web.live_progress] Elapsed time from a recorded start; null (shown as Not recorded) when no start is recorded.
  function elapsedSince(start, now = Date.now()) {
    const begin = instant(start);
    const reference = instant(now);
    if (!begin || !reference) return null;
    return Math.max(0, reference.getTime() - begin.getTime());
  }
  const FINISHED_NODE_STATES = new Set(["Completed", "Failed", "Cancelled", "Skipped"]);
  function nodeProgress(nodes) {
    const rows = Array.isArray(nodes) ? nodes.filter((node) => node && typeof node === "object") : [];
    return Object.freeze({ complete: rows.filter((node) => FINISHED_NODE_STATES.has(node.state)).length, total: rows.length });
  }

  // r[impl kiln.web.runs_table] Local calendar day for grouping; null when no instant is recorded.
  function localDay(value, now = Date.now()) {
    const date = instant(value);
    const reference = instant(now);
    if (!date || !reference) return null;
    const key = (day) => `${day.getFullYear()}-${String(day.getMonth() + 1).padStart(2, "0")}-${String(day.getDate()).padStart(2, "0")}`;
    const yesterday = new Date(reference.getFullYear(), reference.getMonth(), reference.getDate() - 1);
    const dayKey = key(date);
    const label = dayKey === key(reference) ? "Today" : dayKey === key(yesterday) ? "Yesterday" : dayDate.format(date);
    return Object.freeze({ key: dayKey, label });
  }

  // r[impl kiln.highlight.render] Server syntax highlighting (kiln.highlight.v1) becomes inert
  // fragments. Tokens are [start, end, class] in UTF-16 code units; their fragments, with the plain
  // gaps between them, concatenate to the line exactly. Anything malformed renders plain with a note.
  const HIGHLIGHT_SCHEMA = "kiln.highlight.v1";
  const TOKEN_CLASSES = new Set(["keyword", "string", "comment", "number", "constant", "type", "function", "macro", "attribute", "property", "variable", "operator", "punctuation", "tag", "escape", "heading", "link"]);
  const SKIP_REASONS = Object.freeze({
    unsupported_language: "language not supported",
    binary: "binary content",
    too_large: "larger than the highlighting bound",
    parse_error: "the grammar could not parse it",
    truncated_input: "the input was truncated",
  });
  const LANGUAGE_LABELS = Object.freeze({ rust: "Rust", javascript: "JavaScript", typescript: "TypeScript", tsx: "TSX", python: "Python", nix: "Nix", nickel: "Nickel", toml: "TOML", json: "JSON", yaml: "YAML", css: "CSS", html: "HTML", bash: "Bash", markdown: "Markdown", c: "C", go: "Go" });
  const isHighSurrogate = (code) => code >= 0xd800 && code <= 0xdbff;
  const isLowSurrogate = (code) => code >= 0xdc00 && code <= 0xdfff;
  // An offset between the two code units of one astral character would split it.
  const splitsCharacter = (text, offset) => offset > 0 && offset < text.length && isHighSurrogate(text.charCodeAt(offset - 1)) && isLowSurrogate(text.charCodeAt(offset));
  // One line: { fragments: [{ text, kind }] } or { problem } when the tokens are not sorted,
  // non-overlapping, non-empty, in-range integer spans of a known class.
  function tokenFragments(line, tokens) {
    const text = typeof line === "string" ? line : "";
    if (!Array.isArray(tokens)) return { problem: "its tokens are not a list" };
    const fragments = [];
    let offset = 0;
    for (const token of tokens) {
      if (!Array.isArray(token) || token.length !== 3) return { problem: "a token is not [start, end, class]" };
      const [start, end, kind] = token;
      if (!Number.isSafeInteger(start) || !Number.isSafeInteger(end)) return { problem: "a token offset is not an integer" };
      if (start < offset) return { problem: "tokens overlap or are out of order" };
      if (end <= start || end > text.length) return { problem: "a token is empty or outside the line" };
      if (splitsCharacter(text, start) || splitsCharacter(text, end)) return { problem: "a token splits a character" };
      if (typeof kind !== "string" || !TOKEN_CLASSES.has(kind)) return { problem: "a token class is unknown" };
      if (start > offset) fragments.push({ text: text.slice(offset, start), kind: null });
      fragments.push({ text: text.slice(start, end), kind });
      offset = end;
    }
    if (offset < text.length) fragments.push({ text: text.slice(offset), kind: null });
    return { fragments };
  }
  // A whole view: `lines` are the texts the highlight's token lines address, in order.
  // state "highlighted" carries one fragment list per line; "skipped" and "invalid" carry a note and
  // no fragments, so the view renders every line plain.
  function highlightLines(highlight, lines) {
    const texts = Array.isArray(lines) ? lines : [];
    const invalid = (reason) => ({ state: "invalid", language: null, note: `Highlighting unavailable: ${reason}.`, fragments: null });
    if (!highlight || typeof highlight !== "object") return invalid("the response carried no highlighting");
    if (highlight.schema !== HIGHLIGHT_SCHEMA) return invalid("the highlighting schema is not recognised");
    const language = highlight.language ?? null;
    if (language !== null && typeof language !== "string") return invalid("the highlighting language is malformed");
    if (highlight.status === "skipped") {
      if (!Object.hasOwn(SKIP_REASONS, highlight.reason)) return invalid("the skip reason is not recognised");
      if (!Array.isArray(highlight.lines) || highlight.lines.length) return invalid("skipped highlighting carried tokens");
      return { state: "skipped", language, note: `Not highlighted: ${SKIP_REASONS[highlight.reason]}.`, fragments: null };
    }
    if (highlight.status !== "highlighted") return invalid("the highlighting status is not recognised");
    if (!Array.isArray(highlight.lines)) return invalid("the token lines are not a list");
    if (highlight.lines.length !== texts.length) return invalid(`${highlight.lines.length} token lines do not match ${texts.length} text lines`);
    const fragments = [];
    for (let index = 0; index < texts.length; index++) {
      const result = tokenFragments(texts[index], highlight.lines[index]);
      if (result.problem) return invalid(`on line ${index + 1}, ${result.problem}`);
      fragments.push(result.fragments);
    }
    return { state: "highlighted", language, note: null, fragments };
  }
  // The fragments of the same text from UTF-16 offset `from` on (a diff line without its marker).
  function fragmentsFrom(fragments, from) {
    const result = [];
    let offset = 0;
    for (const fragment of Array.isArray(fragments) ? fragments : []) {
      const end = offset + fragment.text.length;
      if (end > from) result.push(offset >= from ? fragment : { text: fragment.text.slice(from - offset), kind: fragment.kind });
      offset = end;
    }
    return result;
  }
  function languageLabel(language) { return typeof language === "string" && language ? LANGUAGE_LABELS[language] || language : "Plain text"; }
  // Appends fragments as text nodes and tok-<class> spans; text is only ever textContent.
  function appendFragments(parent, fragments) {
    for (const fragment of fragments) {
      if (!fragment.kind) { parent.append(document.createTextNode(fragment.text)); continue; }
      const span = document.createElement("span");
      span.className = `tok-${fragment.kind}`;
      span.textContent = fragment.text;
      parent.append(span);
    }
    return parent;
  }

  window.KilnUi = Object.freeze({ outcomeStatus, statusPill, formatDuration, durationElement, formatRelative, timeElement, icon, statusIcon, hydrateIcons, disclosureSummary, errorLines, durationPoints, elapsedSince, nodeProgress, localDay, tokenFragments, highlightLines, fragmentsFrom, languageLabel, appendFragments });
  if (typeof document !== "undefined") hydrateIcons(document);
})();
