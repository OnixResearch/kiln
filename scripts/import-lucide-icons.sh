#!/usr/bin/env bash
set -euo pipefail

# Import the reviewed Lucide icons for the live console from one pinned GPUI Kit
# revision. Every check runs before any file changes; generated data is
# byte-identical across runs.
# r[impl kiln.web.design_system]
# r[impl kiln.web.design_system.scenario.provenance]
root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
revision=944803984cf0ba3111861d6e1aa9d6265c109ff9
nar_hash='sha256-/w0H0zmgKPf+8aAFw3BOT8ifKl2xH+wdVKGEbSwXlRM='
destination="$root/crates/kiln-web-service/src"
list="$destination/icons.list"

refuse() {
  printf 'refusing Lucide import: %s\n' "$1" >&2
  exit 1
}

[[ -s "$list" ]] || refuse "missing or empty icon list $list"
if ! LC_ALL=C sort -u --check=quiet "$list"; then
  refuse "icons.list must be sorted and unique (LC_ALL=C)"
fi
mapfile -t names <"$list"
for name in "${names[@]}"; do
  [[ "$name" =~ ^[a-z0-9]+(-[a-z0-9]+)*$ ]] || refuse "invalid icon name '$name'"
done

metadata=$(nix flake metadata --json "github:longbridge/gpui-kit/$revision")
if ! jq -e --arg rev "$revision" --arg nar "$nar_hash" \
  '.locked.rev == $rev and .locked.narHash == $nar' <<<"$metadata" >/dev/null; then
  refuse "GPUI Kit source with unexpected revision or NAR identity"
fi
source=$(jq -er '.path' <<<"$metadata")
# Metadata may not realise the store path; prefetch does, and must agree on identity.
prefetch=$(nix flake prefetch --json "github:longbridge/gpui-kit/$revision")
if ! jq -e --arg rev "$revision" --arg nar "$nar_hash" --arg path "$source" \
  '.locked.rev == $rev and .hash == $nar and .storePath == $path' <<<"$prefetch" >/dev/null; then
  refuse "prefetched GPUI Kit source disagrees with the pinned identity"
fi
icons="$source/crates/assets/assets/icons"
license="$source/crates/assets/LICENSE-LUCIDE"
[[ -f "$license" ]] || refuse "missing $license"
for name in "${names[@]}"; do
  [[ -f "$icons/$name.svg" ]] || refuse "icon '$name' is not in GPUI Kit $revision"
done

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
list_hash=$(b3sum --no-names "$list")
for name in "${names[@]}"; do
  printf '%s %s\n' "$name" "$(b3sum --no-names "$icons/$name.svg")"
done >"$work/hashes"

python3 - "$icons" "$work/hashes" "$work/icons.js" "$revision" "$nar_hash" "$list_hash" <<'PY'
import json
import sys
import xml.etree.ElementTree as ET

icons, hashes, output, revision, nar_hash, list_hash = sys.argv[1:]
SVG = "{http://www.w3.org/2000/svg}"
# The console builder fixes these presentation attributes; refuse any icon that differs.
ROOT = {"viewBox": "0 0 24 24", "fill": "none", "stroke": "currentColor", "stroke-width": "2",
        "stroke-linecap": "round", "stroke-linejoin": "round", "width": "24", "height": "24"}
SHAPES = {"path": {"d"}, "circle": {"cx", "cy", "r"}, "ellipse": {"cx", "cy", "rx", "ry"},
          "line": {"x1", "x2", "y1", "y2"}, "rect": {"x", "y", "width", "height", "rx", "ry"},
          "polyline": {"points"}, "polygon": {"points"}}

def refuse(message):
    sys.stderr.write(f"refusing Lucide import: {message}\n")
    sys.exit(1)

entries = []
lines = [line.split(" ") for line in open(hashes, encoding="utf-8").read().splitlines()]
for name, digest in lines:
    root = ET.parse(f"{icons}/{name}.svg").getroot()
    if root.tag != f"{SVG}svg" or dict(root.attrib) != ROOT or (root.text or "").strip():
        refuse(f"{name}.svg has unexpected root presentation attributes")
    shapes = []
    for child in root:
        tag = child.tag.removeprefix(SVG)
        if tag not in SHAPES or len(child) or (child.text or "").strip():
            refuse(f"{name}.svg contains unsupported element <{tag}>")
        if not set(child.attrib) <= SHAPES[tag] or not child.attrib:
            refuse(f"{name}.svg <{tag}> has unsupported attributes {sorted(child.attrib)}")
        shapes.append([tag, dict(child.attrib)])
    if not shapes:
        refuse(f"{name}.svg has no drawable elements")
    entries.append((name, digest, shapes))

def js(value):
    return json.dumps(value, ensure_ascii=True, separators=(", ", ": "))

with open(output, "w", encoding="utf-8", newline="\n") as out:
    out.write("// Generated by scripts/import-lucide-icons.sh from crates/kiln-web-service/src/icons.list; do not edit.\n")
    out.write(f"// Source: GPUI Kit {revision} (NAR {nar_hash}), crates/assets/assets/icons.\n")
    out.write("// Lucide icons: ISC License; Feather-derived icons: MIT License. See LICENSE-LUCIDE.\n")
    out.write(f"// icons.list BLAKE3: {list_hash}\n")
    out.write("// Source SVG BLAKE3:\n")
    for name, digest, _ in entries:
        out.write(f"//   {name}.svg {digest}\n")
    out.write("// Data only: each icon is a list of [element, attributes] descriptors; KilnUi.icon builds the SVG.\n")
    out.write("// r[impl kiln.web.design_system]\n")
    out.write('"use strict";\n')
    out.write("window.KilnIcons = Object.freeze({\n")
    for name, _, shapes in entries:
        frozen = ", ".join(f"Object.freeze([{js(tag)}, Object.freeze({js(attributes)})])" for tag, attributes in shapes)
        out.write(f"  {js(name)}: Object.freeze([{frozen}]),\n")
    out.write("});\n")
PY

install -m 0644 "$work/icons.js" "$destination/icons.js"
install -m 0644 "$license" "$destination/LICENSE-LUCIDE"
printf 'imported %d Lucide icons from GPUI Kit %s (%s)\n' "${#names[@]}" "$revision" "$nar_hash"
